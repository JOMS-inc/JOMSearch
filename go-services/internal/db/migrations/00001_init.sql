-- Initial PostgreSQL schema, ported from the SQLite schema (schema/schema.sql).
-- goose runs everything between "Up" and "Down" in one transaction, and
-- records the version in goose_db_version so it never runs twice.

-- +goose Up
CREATE TABLE users (
    -- BY DEFAULT (not ALWAYS) so cmd/sqlite2pg can copy the old ids as-is.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE, -- UNIQUE creates the index used by login
    email TEXT NOT NULL UNIQUE,    -- and the one used to look up the session user
    password TEXT NOT NULL,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE pages (
    title TEXT PRIMARY KEY,
    url TEXT NOT NULL UNIQUE,
    language TEXT NOT NULL DEFAULT 'en' CHECK (language IN ('en', 'da')),
    last_updated TIMESTAMPTZ,
    content TEXT NOT NULL,

    -- Full-text search document, kept up to date by Postgres itself (this
    -- replaces the SQLite FTS5 table and its three triggers).
    -- Each page is stemmed in its own language, so "programs" matches
    -- "program" and "byer" matches "by". Title words weigh more (A) than
    -- content words (B) when ranking.
    search TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector(CASE language WHEN 'da' THEN 'danish'::regconfig ELSE 'english'::regconfig END, title), 'A') ||
        setweight(to_tsvector(CASE language WHEN 'da' THEN 'danish'::regconfig ELSE 'english'::regconfig END, content), 'B')
    ) STORED
);

-- GIN is an inverted index: for every word it stores which rows contain it,
-- so a search only reads the matching pages instead of scanning all of them.
CREATE INDEX pages_search_idx ON pages USING GIN (search);

-- Searches the crawler already handled (see cmd/crawler).
CREATE TABLE crawled_terms (
    query TEXT NOT NULL,
    language TEXT NOT NULL,
    crawled_at TIMESTAMPTZ NOT NULL,
    pages_added INTEGER NOT NULL,
    PRIMARY KEY (query, language)
);

-- +goose Down
DROP TABLE crawled_terms;
DROP TABLE pages;
DROP TABLE users;
